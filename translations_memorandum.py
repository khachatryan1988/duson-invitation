def normalize_language(lang):
    if not lang:
        return DEFAULT_LANGUAGE

    lang = str(lang).lower().strip()

    if lang not in SUPPORTED_LANGUAGES:
        return DEFAULT_LANGUAGE

    return lang


def get_translation(lang):
    lang = normalize_language(lang)
    return TRANSLATIONS[lang]